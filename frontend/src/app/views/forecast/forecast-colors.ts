// Цвета графиков. Категориальная палитра проверена валидатором (CVD, светлота, насыщенность) на белой поверхности;
// порядок фиксирован, цвет закрепляется за каналом и не зависит от фильтров. Синий (слот 1) зарезервирован
// под акцент: прогноз, рекомендация, выбранная модель — поэтому каналы начинаются со слота 2.

export const FC_COLORS = {
  surface: '#ffffff',
  ink: '#0b0b0b',
  inkSecondary: '#52514e',
  muted: '#898781',
  grid: '#e1e0d9',
  axis: '#c3c2b7',
  /** Акцент: прогноз, рекомендация, чемпион. */
  accent: '#2a78d6',
  accentWash: 'rgba(42, 120, 214, 0.12)',
  accentTrack: '#cde2fb',
  /** Нейтральный: «база без маркетинга», план, «прочее». */
  neutral: '#b9b7ae',
  zone: 'rgba(137, 135, 129, 0.07)',
  /** Каналы по порядку: оранжевый, аква, жёлтый, маджента, зелёный, фиолетовый, красный, синий. */
  channels: ['#eb6834', '#1baf7a', '#eda100', '#e87ba4', '#008300', '#4a3aa7', '#e34948', '#2a78d6']
};

/** Цвет канала по его позиции в списке каналов модели; сверх восьми — нейтральный. */
export function channelColor(code: string, codes: string[]): string {
  const index = codes.indexOf(code);
  return index >= 0 && index < FC_COLORS.channels.length ? FC_COLORS.channels[index] : FC_COLORS.neutral;
}
