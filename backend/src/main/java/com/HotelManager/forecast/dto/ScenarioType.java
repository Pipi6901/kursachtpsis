package com.HotelManager.forecast.dto;

/** Сценарий маркетинговых затрат на период прогноза. */
public enum ScenarioType {
    /** План: запланированные кампании как есть. */
    PLAN,
    /** Затраты на период прогноза отключены (эффект прошлых кампаний ещё затухает). */
    NO_MARKETING,
    /** Свой сценарий: множители к плану и/или постоянные недельные затраты по каналам. */
    CUSTOM
}
