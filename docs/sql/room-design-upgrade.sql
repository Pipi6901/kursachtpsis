-- Несколько фотографий, удобства, площадь и вид из окна у номера (редизайн сайта, версия 2).
--
-- Сервер создаёт всё это сам при запуске (Hibernate, ddl-auto=update; перенос прежних фотографий выполняет класс
-- RoomImageBackfill), поэтому вручную запускать скрипт не нужно. Он приведён для администратора БД, который применяет
-- изменения под своей учётной записью:
--   psql -U postgres -d hotel -f docs/sql/room-design-upgrade.sql
--
-- Что меняется (данные существующих номеров не изменяются, строки только добавляются в новые таблицы):
--   * в таблицу room добавляются необязательные столбцы area (площадь, м²) и view_type (вид из окна);
--   * создаётся таблица room_image – фотографии номера по порядку (position), первая – обложка карточки;
--   * создаётся таблица room_amenity – удобства номера (коды: WIFI, AC, TV …);
--   * фото из прежнего поля room.photo переносится в room_image первой фотографией (если ещё не перенесено).
-- Возврат к прежнему оформлению сайта эти таблицы не затрагивает: прежний клиент их просто не использует.
-- Скрипт можно выполнять повторно.
-- =============================================================================
ALTER TABLE room ADD COLUMN IF NOT EXISTS area INTEGER;
ALTER TABLE room ADD COLUMN IF NOT EXISTS view_type VARCHAR(60);

CREATE TABLE IF NOT EXISTS room_image (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id   BIGINT       NOT NULL REFERENCES room (room_id),
    file_name VARCHAR(300) NOT NULL,
    position  INTEGER      NOT NULL
);

CREATE TABLE IF NOT EXISTS room_amenity (
    room_id BIGINT      NOT NULL REFERENCES room (room_id),
    amenity VARCHAR(40) NOT NULL,
    PRIMARY KEY (room_id, amenity)
);

-- перенос единственного фото прежних номеров
INSERT INTO room_image (room_id, file_name, position)
SELECT r.room_id, r.photo, 0
FROM room r
WHERE r.photo IS NOT NULL AND r.photo <> ''
  AND NOT EXISTS (SELECT 1 FROM room_image i WHERE i.room_id = r.room_id);

