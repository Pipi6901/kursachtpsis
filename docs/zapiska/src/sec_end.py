def read_listing(rel):
    with open(os.path.join(REPO, rel), encoding='utf-8') as fh:
        lines = [ln.rstrip() for ln in fh.read().replace('\r\n', '\n').split('\n')]
    while lines and not lines[-1]:
        lines.pop()
    return '\n'.join(lines)


