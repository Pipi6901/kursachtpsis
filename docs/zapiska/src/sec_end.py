def _cell(text, w, jc='left', bold=False, span=1, underline=False):
    runs = E.inline(text, bold=bold, size=24, font=True) if text else ''
    ppr = f'<w:spacing w:after="0"/><w:jc w:val="{jc}"/>'
    tcpr = f'<w:tcW w:w="{w}" w:type="dxa"/>' + (f'<w:gridSpan w:val="{span}"/>' if span > 1 else '')
    return f'<w:tc><w:tcPr>{tcpr}<w:vAlign w:val="center"/></w:tcPr><w:p><w:pPr>{ppr}</w:pPr>{runs}</w:p></w:tc>'


def _row(cells, height=None):
    trpr = '<w:cantSplit/>' + (f'<w:trHeight w:val="{height}" w:hRule="atLeast"/>' if height else '')
    return f'<w:tr><w:trPr>{trpr}</w:trPr>{"".join(cells)}</w:tr>'


